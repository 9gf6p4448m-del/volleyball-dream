const FRAME_YAW0 = 0.8967;   // 該段起始 yaw（量測值）
const FRAME_DT = 0.009667;   // 該段實際幀時距（58 ticks ÷ 60 ÷ 100 幀）

// 用給定的目標朝向函式重演整段，回傳累積轉角（每幀 |Δyaw| 總和，rad）等指標
function replay({ maxRate = FACING.MAX_TURN_RATE, target = facingTarget } = {}) {
  let yaw = FRAME_YAW0;
  let travel = 0;
  let maxStep = 0;
  let maxTargetJump = 0;
  let prevTarget = null;
  for (const [x, z, ballX, ballZ, ballDx, ballDz] of FRAMES) {
    const t = target({
      phase: 'rally', netYaw: 0, blockDuty: false,
      x, z, ballX, ballZ, ballDx, ballDz, simDt: SIM_DT, currentYaw: yaw,
    });
    if (prevTarget !== null) {
      maxTargetJump = Math.max(maxTargetJump, Math.abs(shortestArc(prevTarget, t)));
    }
    prevTarget = t;
    const next = approachYaw(yaw, t, FRAME_DT, maxRate);
    const step = Math.abs(next - yaw);
    travel += step;
    maxStep = Math.max(maxStep, step);
    yaw = next;
  }
  return { travel, maxStep, maxTargetJump };
}

// ① 核心：實測「會轉圈」的序列，累積轉角不得超過 180°
test('朝向 — 實測扣球序列不再繞圈（舊版 343°）', () => {
  const { travel } = replay();
  assert.ok(travel * DEG <= 180,
    `累積轉角 ${(travel * DEG).toFixed(1)}° 應 <= 180°（舊版 343°）`);
});

// 對照：同一段餵舊版邏輯必須重現繞圈——證明測資本身有咬合力，不是無論如何都會過
test('朝向 — 舊版邏輯重演同一序列會繞滿一圈（測資有效性對照）', () => {
  const legacyTarget = (o) => {
    const dx = o.ballX - o.x; const dz = o.ballZ - o.z;
    if (Math.hypot(dx, dz) > 1.1) return Math.atan2(dx, dz);
    return Math.hypot(o.ballDx, o.ballDz) > 1e-4
      ? Math.atan2(-o.ballDx, -o.ballDz) : o.currentYaw;
  };
  const { travel } = replay({ maxRate: Infinity, target: legacyTarget });
  assert.ok(travel * DEG > 300,
    `舊版應重現繞圈，實得 ${(travel * DEG).toFixed(1)}°`);
});

// ② 距離跨越舊門檻 1.1m 前後，目標朝向的單幀跳變要有上限
test('朝向 — 跨越 1.1m 不再硬跳（實測序列單幀目標跳變 < 15°）', () => {
  const { maxTargetJump } = replay();
  assert.ok(maxTargetJump * DEG < 15,
    `單幀目標跳變 ${(maxTargetJump * DEG).toFixed(1)}° 應 < 15°`);
});

test('朝向 — 距離帶連續：球等速穿過 NEAR_R..FAR_R，目標角無階梯跳變', () => {
  // 球以 12 m/s（遠高於可信門檻）飛來，球員站原點；球由遠而近逐步逼近
  let prev = null; let maxJump = 0;
  for (let dist = FACING.FAR_R + 0.4; dist > 0.2; dist -= 0.005) {
    const t = facingTarget({
      phase: 'rally', netYaw: 0, blockDuty: false,
      x: 0, z: 0, ballX: 0.6 * dist, ballZ: 0.8 * dist,
      ballDx: 0, ballDz: -12 * SIM_DT, simDt: SIM_DT, currentYaw: 0,
    });
    if (prev !== null) maxJump = Math.max(maxJump, Math.abs(shortestArc(prev, t)));
    prev = t;
  }
  assert.ok(maxJump * DEG < 3,
    `每 5mm 位移的目標角跳變 ${(maxJump * DEG).toFixed(2)}° 應 < 3°（連續混合）`);
});

// ③ 球速趨近 0 時不得用它決定朝向
test('朝向 — 球幾乎不動時改看球的位置，不看雜訊般的球速方向', () => {
  // 球在球員正前方 0.5m（近身帶內），每 tick 只位移 0.0002m（0.012 m/s）且方向朝 -z
  // 舊版會據此面向 +z（180° 反向）
  const t = facingTarget({
    phase: 'rally', netYaw: 0, blockDuty: false,
    x: 0, z: 0, ballX: 0, ballZ: 0.5,
    ballDx: 0, ballDz: -0.0002, simDt: SIM_DT, currentYaw: 0,
  });
  assert.ok(Math.abs(shortestArc(t, 0)) < 1e-9, `應面向球的位置（yaw 0），實得 ${t}`);
});

test('朝向 — 舉球弧頂等級的球速（≈1.5 m/s）不足以取代位置朝向', () => {
  // 實測值：二傳舉球最高點每 tick 水平位移 0.020／0.0143
  const t = facingTarget({
    phase: 'rally', netYaw: 0, blockDuty: false,
    x: 0, z: 0, ballX: 0, ballZ: 0.5,
    ballDx: 0.02, ballDz: 0.0143, simDt: SIM_DT, currentYaw: 0,
  });
  assert.equal(t, Math.atan2(0, 0.5), '低於 MIN_BALL_SPEED 應完全退回位置朝向');
});

test('朝向 — 扣球等級的球速（18 m/s）近身時完全採用來球方向', () => {
  const t = facingTarget({
    phase: 'rally', netYaw: 0, blockDuty: false,
    x: 0, z: 0, ballX: 0, ballZ: 0.5,
    ballDx: 0, ballDz: -18 * SIM_DT, simDt: SIM_DT, currentYaw: 0,
  });
  // 球由 +z 往 -z 衝過來 ⇒ 面向 +z＝atan2(0, 18*SIM_DT)＝0
  assert.ok(Math.abs(shortestArc(t, 0)) < 1e-9, `應面向來球方向 0，實得 ${t}`);
});

// ④ 轉速上限生效
test('朝向 — 轉速上限：瞬間 180° 目標，單幀轉不超過 MAX_TURN_RATE × dt', () => {
  const dt = 1 / 60;
  const next = approachYaw(0, Math.PI - 1e-6, dt);
  assert.ok(Math.abs(next) <= FACING.MAX_TURN_RATE * dt + 1e-12,
    `單幀轉了 ${Math.abs(next)} rad，上限 ${FACING.MAX_TURN_RATE * dt}`);
  const uncapped = approachYaw(0, Math.PI - 1e-6, dt, Infinity);
  assert.ok(Math.abs(uncapped) > FACING.MAX_TURN_RATE * dt, '對照：無上限時單幀轉更多');
});

test('朝向 — 轉速上限對稱（負向同樣受限）', () => {
  const dt = 1 / 60;
  const next = approachYaw(0, -Math.PI + 1e-6, dt);
  assert.ok(next <= 0 && Math.abs(next) <= FACING.MAX_TURN_RATE * dt + 1e-12);
});

test('朝向 — 小角度差不受上限影響（不改既有追球手感）', () => {
  const dt = 1 / 60;
  const target = 0.15; // 8.6°：日常追球等級
  assert.equal(approachYaw(0, target, dt), approachYaw(0, target, dt, Infinity),
    '小角度時上限不應咬合');
});

// 角度混合必須走最短弧（±π 邊界）
test('角度混合走最短弧：3.0 與 -3.0 的中點應在 ±π 附近，不是 0', () => {
  const mid = blendAngle(3.0, -3.0, 0.5);
  const wrapped = Math.atan2(Math.sin(mid), Math.cos(mid));
  assert.ok(Math.abs(Math.abs(wrapped) - Math.PI) < 0.15,
    `中點 ${wrapped} 應接近 ±π（直接線性內插會錯給 0）`);
});

// 職責制其餘分支：行為與抽出前等價
test('朝向職責制：攔網職責與非 rally 一律面向網；圍圈權重高時轉向教練', () => {
  const base = {
    x: 1, z: 2, ballX: 1, ballZ: 2.5, ballDx: 0, ballDz: -0.3,
    simDt: SIM_DT, currentYaw: 0, netYaw: Math.PI,
  };
  assert.equal(facingTarget({ ...base, phase: 'rally', blockDuty: true }), Math.PI, '攔網鎖面向網');
  assert.equal(facingTarget({ ...base, phase: 'serve', blockDuty: false }), Math.PI, '非 rally 面向網');
  const coach = facingTarget({
    ...base, phase: 'rally', blockDuty: false,
    huddleW: FACING.HUDDLE_FACE_W + 0.01, coachX: 1, coachZ: 8,
  });
  assert.equal(coach, Math.atan2(0, 6), '圍圈權重高時覆蓋為面向教練');
});
